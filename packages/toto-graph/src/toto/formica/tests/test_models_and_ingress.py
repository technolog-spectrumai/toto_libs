from datetime import timedelta
from io import StringIO

from django.core.management import call_command
from django.test import TestCase
from django.utils import timezone

from toto.formica.models import CasteConfig, Colony, ColonyCycle

from .helpers import make_colony


class ColonyModelTests(TestCase):
    def test_slug_autogenerated_and_unique(self):
        first = Colony.objects.create(name="Colonia Prima")
        second = Colony.objects.create(name="Colonia-Prima!")
        self.assertEqual(first.slug, "colonia-prima")
        self.assertEqual(second.slug, "colonia-prima-1")

    def test_is_due(self):
        now = timezone.now()
        colony = Colony.objects.create(name="C", interval_minutes=60)
        self.assertTrue(colony.is_due(now))  # never ran
        colony.last_run_at = now - timedelta(minutes=30)
        self.assertFalse(colony.is_due(now))
        colony.last_run_at = now - timedelta(minutes=61)
        self.assertTrue(colony.is_due(now))
        colony.paused = True
        self.assertFalse(colony.is_due(now))
        colony.paused = False
        colony.enabled = False
        self.assertFalse(colony.is_due(now))

    def test_has_cycle_in_flight(self):
        colony = Colony.objects.create(name="C")
        self.assertFalse(colony.has_cycle_in_flight())
        cycle = ColonyCycle.objects.create(colony=colony, number=1)
        self.assertTrue(colony.has_cycle_in_flight())
        cycle.status = ColonyCycle.STATUS_COMPLETED
        cycle.save()
        self.assertFalse(colony.has_cycle_in_flight())


class IngressTests(TestCase):
    def _run(self):
        out = StringIO()
        call_command("ingress_formica", stdout=out)
        return out.getvalue()

    def test_seeds_colony_and_castes(self):
        self._run()
        colony = Colony.objects.get(slug="colonia-prima")
        self.assertEqual(colony.name, "Colonia Prima")
        self.assertFalse(colony.trusted)
        caste_keys = set(colony.castes.values_list("caste_key", flat=True))
        self.assertEqual(
            caste_keys, {"scout", "forager", "nurse", "pruner", "architect", "queen"}
        )

    def test_idempotent(self):
        self._run()
        colony = Colony.objects.get(slug="colonia-prima")
        colony.trusted = True
        colony.save()
        config = colony.castes.get(caste_key="forager")
        config.ant_count = 99
        config.save()

        self._run()  # second run must not reset user changes or duplicate
        self.assertEqual(Colony.objects.count(), 1)
        colony.refresh_from_db()
        self.assertTrue(colony.trusted)
        self.assertEqual(colony.castes.get(caste_key="forager").ant_count, 99)
        self.assertEqual(colony.castes.count(), 6)


class ChecksumExclusionTests(TestCase):
    """The one change formica makes outside its app: pheromone markers must
    never flip ravioli's content checksum (else every deposit looks like
    drift and triggers spurious re-syncs)."""

    def test_ph_and_formica_props_are_checksum_neutral(self):
        from toto.ravioli.graph_export import content_checksum

        base = {"name": "Ada", "uuid": "u-1"}
        marked = {
            **base,
            "_ph": 3.2,
            "_ph_material": 1.1,
            "_ph_alarm": 7,
            "_ph_touched": 9,
            "_formica_quarantine": 4,
        }
        self.assertEqual(content_checksum(base), content_checksum(marked))

    def test_content_changes_still_flip_the_checksum(self):
        from toto.ravioli.graph_export import content_checksum

        self.assertNotEqual(
            content_checksum({"name": "Ada"}), content_checksum({"name": "Grace"})
        )


class BudgetInvariantTests(TestCase):
    def test_fake_and_real_graph_ops_share_budget_semantics(self):
        from toto.formica.colony.graph_ops import WriteBudgetExceeded

        from .helpers import FakeGraphOps

        fake = FakeGraphOps(write_budget=3, cycle_number=1)
        fake.deposit_edge_ph([{"eid": "e1", "ph": 1.0}], floor=0, ceiling=10)
        fake.set_alarms(["a", "b"])
        with self.assertRaises(WriteBudgetExceeded):
            fake.quarantine(["c", "d"])
        self.assertEqual(fake.writes_used, 3)
