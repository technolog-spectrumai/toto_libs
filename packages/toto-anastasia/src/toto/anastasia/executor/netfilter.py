"""The packet layer under Smokescreen: what a Capsule can reach at all.

TWO LAYERS, AND NEITHER IS THE OTHER'S BACKUP. Smokescreen decides
DESTINATIONS — it resolves a CONNECT and refuses a host that is not on the
allowlist. This module decides PACKETS — from the egress network, the proxy's
address and port are the only thing routable, so a process that declines to use
the proxy and opens its own socket reaches nothing. Either alone is weak in a
different direction:

* a proxy with no packet filter is advisory. Nothing compels a workload to
  honour ``HTTPS_PROXY``, and a script that opens ``socket(AF_INET)`` is on the
  internet;
* a packet filter with no proxy cannot tell ``pypi.org`` from an exfiltration
  endpoint that answers on 443. Addresses are not identities.

WHY OUR OWN TABLE. Docker writes its rules into ``filter``/``nat`` through the
iptables-nft shim and rewrites them whenever a network or container changes. A
rule added to Docker's chains is a rule Docker may remove. ``inet anastasia`` is
a separate table at an earlier hook priority: Docker does not know it exists and
will not touch it, and it is evaluated before Docker's ``FORWARD`` rules get
their say.

**POLICY IS ACCEPT AND THAT IS DELIBERATE.** A ``policy drop`` on a forward hook
drops every forwarded packet on the host — every other container, every other
stack — the moment this table loads. What is wanted is narrow: packets FROM the
egress subnet are dropped unless they are going to the proxy. Everything not
from that subnet is none of this table's business, and a default that had an
opinion about it would be a host-wide outage waiting for a typo.

FAIL CLOSED means something specific here, and it is not "drop everything". The
executor cannot make the kernel filter packets if ``nft`` is missing or the
table will not load; what it can do is REFUSE TO MOUNT a Capsule that asked for
egress. That is the closed direction — no capsule gets a NIC it cannot have
filtered — and it is what `verify` is for.
"""

from __future__ import annotations

import logging
import shutil
import subprocess

log = logging.getLogger("toto.anastasia.executor.netfilter")

#: The table this module owns, in full. Nothing else writes to it, and
#: `ensure` replaces it wholesale rather than appending — an append-only
#: ruleset accumulates a second copy of every rule on each restart, and the
#: duplicates are invisible until somebody reads the counters.
TABLE = "anastasia"


class NetfilterError(Exception):
    """The ruleset could not be established or could not be proven."""


def _nft(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    binary = shutil.which("nft")
    if not binary:
        raise NetfilterError(
            "nft is not installed, so egress cannot be filtered and no Capsule "
            "may be given a network. Install nftables, or turn egress off.")
    proc = subprocess.run([binary, *args], capture_output=True, text=True,
                          check=False)
    if check and proc.returncode != 0:
        raise NetfilterError(
            f"nft {' '.join(args)} failed: {proc.stderr.strip()[-400:]}")
    return proc


def ruleset(bridge: str, subnet: str, proxy_ip: str, proxy_port: int) -> str:
    """The whole table, as one atomic `nft -f` document.

    MATCHED ON THE INTERFACE, NOT THE SOURCE ADDRESS. `ip saddr 10.207.0.0/24
    drop` reads correctly and is weak: the source address is a field the sender
    fills in, and a workload that can open a raw socket can put anything there.
    `iifname` is the interface the packet physically arrived on, which is not
    something inside the container can choose. That is also why the bridge has
    a PINNED name — Docker's generated `br-<hash>` is not knowable in advance,
    and nft has no wildcard for `iif` (only `iifname` accepts one, and an
    invalid `iif "br-*"` makes the kernel reject the ENTIRE ruleset, leaving
    nothing filtered at all).

    THE PROXY IS EXEMPTED FIRST, and forgetting that made the first draft of
    this file unusable: the proxy's own address is inside the subnet, so a
    blanket drop on the subnet dropped the proxy's outbound connections too and
    nothing could ever be fetched. Its egress is the entire point of it.

    THREE CHAINS, because there are three ways off a bridge and a rule in one
    cannot see the others:

    * ``forward`` — capsule to anywhere off this bridge (routed).
    * ``input``   — capsule to THIS HOST, including whatever else it runs.
      Host-destined packets never traverse `forward`, so a filter with only a
      forward chain leaves every service on the host reachable.
    * ``bridge``  — capsule to capsule (switched, same subnet). These frames
      are never routed, so neither IP chain sees them.
    """
    return f"""\
# Generated by toto.anastasia.executor.netfilter — do not edit by hand.
# Replaced wholesale, in one transaction, every time the executor starts.

# Create-then-delete so the real definition below always replaces rather than
# appends. `nft -f` ADDS to an existing table, so without this every restart
# would leave a second copy of every rule — invisible until somebody reads the
# counters, and wrong the moment the two copies differ.
table inet {TABLE} {{}}
delete table inet {TABLE}
table bridge {TABLE} {{}}
delete table bridge {TABLE}

table inet {TABLE} {{
    chain forward {{
        # priority -10: before Docker's own FORWARD rules (filter, 0), so a
        # drop here is final. policy accept: this table judges ONE interface
        # and nothing else — a `policy drop` on a forward hook would drop every
        # forwarded packet on the host, every other container, every stack.
        type filter hook forward priority -10; policy accept;

        # The proxy reaching the internet. FIRST, because its address is inside
        # the subnet the drop below matches, and without this the proxy cannot
        # fetch anything and the whole feature is dead.
        iifname "{bridge}" ip saddr {proxy_ip} accept

        # Everything else that arrives on this bridge and wants to be routed
        # off it. This is the rule that makes the proxy compulsory rather than
        # advisory: a raw socket to an address, DNS to the world, the cloud
        # metadata address and another stack's database all land here.
        iifname "{bridge}" drop
    }}

    chain input {{
        # THE HOST ITSELF. A packet addressed to this machine — its bridge
        # gateway, its tailnet address, a database bound to 0.0.0.0 — is
        # delivered locally and never passes the forward hook. Without this
        # chain the filter above stops a capsule reaching the internet and
        # leaves it able to reach everything the host runs.
        type filter hook input priority -10; policy accept;
        iifname "{bridge}" drop
    }}
}}

# CAPSULE TO CAPSULE is a separate table because it is a separate problem.
# Two containers on one bridge in one subnet talk at layer 2: the frames are
# SWITCHED, never routed, so they do not pass either chain above. Docker's own
# `enable_icc=false` would stop it and cannot be used — the proxy is a
# container on that bridge too, so disabling inter-container traffic would
# disable the proxy.
#
# Every rule is scoped to this bridge on BOTH sides. An unscoped rule in the
# bridge family applies to every bridge on the host, which would filter other
# stacks' networks as a side effect of turning egress on for this one.
table bridge {TABLE} {{
    chain forward {{
        type filter hook forward priority -200; policy accept;

        # To and from the proxy: the whole reason this bridge exists.
        iifname "{bridge}" oifname "{bridge}" ip daddr {proxy_ip} accept
        iifname "{bridge}" oifname "{bridge}" ip saddr {proxy_ip} accept

        # Anything else crossing this bridge, at any protocol. Not just IPv4:
        # link-local IPv6 exists on an interface whether or not Docker assigned
        # an address, and a v6-only drop written as an afterthought is how two
        # capsules end up with a private channel nobody filtered.
        iifname "{bridge}" oifname "{bridge}" drop
    }}
}}
"""


def ensure(bridge: str, subnet: str, proxy_ip: str, proxy_port: int) -> None:
    """Install the ruleset, replacing any earlier copy, in ONE transaction.

    The whole document goes to a single `nft -f -`, which nftables applies
    atomically: either every table is replaced or nothing changes. The earlier
    version of this function deleted the tables first in separate calls, which
    left a window with nothing filtered — and, worse, left the host UNFILTERED
    if the load then failed. The create-then-delete preamble inside the
    document is what makes one transaction able to replace a table that may or
    may not already exist.
    """
    document = ruleset(bridge, subnet, proxy_ip, proxy_port)
    binary = shutil.which("nft")
    if not binary:
        raise NetfilterError(
            "nft is not installed, so egress cannot be filtered and no Capsule "
            "may be given a network. Install nftables, or turn egress off.")
    proc = subprocess.run([binary, "-f", "-"], input=document,
                          capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise NetfilterError(
            f"the egress ruleset would not load: {proc.stderr.strip()[-400:]}")
    log.info("anastasia: egress filtered — %s may reach %s:%s and nothing else",
             bridge, proxy_ip, proxy_port)


#: The rules `verify` insists on finding, as nft echoes them back. Kept beside
#: the ruleset so a rule renamed in one and not the other fails loudly here
#: rather than silently weakening what is checked.
def _required(bridge: str, proxy_ip: str):
    return (
        ("inet", f'iifname "{bridge}" ip saddr {proxy_ip} accept'),
        ("inet", f'iifname "{bridge}" drop'),
        ("bridge", f'iifname "{bridge}" oifname "{bridge}" drop'),
    )


def verify(bridge: str, subnet: str, proxy_ip: str, proxy_port: int) -> None:
    """Prove the rules are in the kernel right now. Raises if they are not.

    READ BACK FROM THE KERNEL, never remembered from `ensure`. The failure this
    guards is not "we forgot to call ensure" — it is the ruleset being flushed
    AFTERWARDS by something else on the host, which is exactly what a
    `systemctl restart nftables` or an operator's `nft flush ruleset` does.

    CALLED BEFORE EVERY MOUNT, not once at startup. A check that ran only at
    boot would prove the filter existed at boot and nothing about the moment a
    Capsule is actually given a NIC — and the window between those two is
    measured in days.
    """
    for family, rule in _required(bridge, proxy_ip):
        listed = _nft("list", "table", family, TABLE).stdout
        # Whitespace-normalised: nft echoes its own formatting, which is not
        # byte-identical to what was written.
        if " ".join(rule.split()) not in " ".join(listed.split()):
            raise NetfilterError(
                f"the egress ruleset is not in the kernel as written (missing "
                f"from the {family} table: {rule}). Refusing to give a Capsule "
                "a network it cannot have filtered.")


def available() -> bool:
    """Whether this host could filter at all. For preflight, not for gating."""
    return shutil.which("nft") is not None
