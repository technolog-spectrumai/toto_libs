from django.utils import timezone
from django.contrib.auth.models import User
from lorem_text import lorem
from oya.ingress import IngressCommand
from documents.models import (
    Tag, Department,
    HTMLPreset, LatexPreset,
    HTMLDocument, HTMLSection, HTMLSubSection,
    LatexDocument, LatexSection, LatexSubSection
)
from documents.models import LatexDocumentFactory, LatexScratchpad



class Command(IngressCommand):
    help = "Seed HTML and LaTeX documents with sections and subsections using existing users"

    def process(self, _):
        self.create_dashboard_item(
            title="Documents",
            icon="file-text",
            description="HTML and LaTeX presets, departments, and structured documents with sections and subsections.",
            link="/documents/"
        )

        self.stdout.write("🚀 Starting document ingress...")

        users = list(User.objects.all())
        if not users:
            self.stdout.write(self.style.ERROR("❌ No users found. Create at least one user before running ingress."))
            return

        # 📌 Tags
        tag_names = ['Research', 'Internal', 'Public', 'Confidential', 'Draft']
        tags = [Tag.objects.get_or_create(name=name)[0] for name in tag_names]

        # 🏢 Departments
        departments = [
            Department.objects.create(
                name=f"Department {i+1}",
                owner=users[i % len(users)],
                copyright_holder="SpectrumAi.pl",
                copyright_notice=(
                    "This document is confidential and intended solely for the use "
                    "of the individual or entity to whom it is addressed. "
                    "Unauthorized distribution, reproduction, or disclosure is strictly prohibited."
                )
            )
            for i in range(3)
        ]

        # 🎨 Presets
        html_preset = HTMLPreset.objects.create(
            name="HTML Preset",
            description="Default HTML setup",
            template_name="template.html",
            css_classes={"body": "bg-white text-black", "header": "font-bold"},
            footer_html="<footer>Generated by Copilot</footer>"
        )

        latex_preset = LatexPreset.objects.create(
            name="LaTeX Preset",
            description="Default LaTeX setup",
            document_class='article',
            preamble="",
            packages=["amsmath", "geometry", "graphicx"],
            footer_note=lorem.sentence()
        )

        # 📄 Create LaTeX Documents
        latex_docs = []
        for i in range(4):
            latex_doc = LatexDocument.objects.create(
                title=f"LaTeX Document {i+1}",
                summary=lorem.sentence(),
                created_by=users[i % len(users)],
                department=departments[i % len(departments)],
                created_at=timezone.now(),
                preset=latex_preset
            )
            latex_doc.tags.set(tags)
            latex_docs.append(latex_doc)

            # Add sections and subsections
            for j in range(2):
                section = LatexSection.objects.create(
                    document=latex_doc,
                    title=f"Section {j+1}",
                    order=j,
                    content=lorem.paragraph()
                )
                for k in range(2):
                    LatexSubSection.objects.create(
                        section=section,
                        order=k,
                        title=f"SubSection {j+1}.{k+1}",
                        content=lorem.paragraph()
                    )

        # 🌐 Create HTML Documents and link to LaTeX
        for i in range(4):
            html_doc = HTMLDocument.objects.create(
                title=f"HTML Document {i+1}",
                summary=lorem.sentence(),
                created_by=users[i % len(users)],
                department=departments[i % len(departments)],
                created_at=timezone.now(),
                preset=html_preset,
                linked_latex=latex_docs[i]  # 🔗 Link to LaTeX version
            )
            html_doc.tags.set(tags)

            # Add sections and subsections
            for j in range(2):
                section = HTMLSection.objects.create(
                    document=html_doc,
                    title=f"Section {j+1}",
                    order=j,
                    content=lorem.paragraph()
                )
                for k in range(2):
                    HTMLSubSection.objects.create(
                        section=section,
                        order=k,
                        title=f"SubSection {j+1}.{k+1}",
                        content=lorem.paragraph()
                    )

        self.stdout.write(self.style.SUCCESS("✅ Ingress complete. HTML and LaTeX documents seeded with full structure."))
