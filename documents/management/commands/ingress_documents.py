import random
from django.utils import timezone
from django.contrib.auth.models import User
from lorem_text import lorem
from oya.ingress import IngressCommand
from documents.models import (
    Tag, Department,
    LatexPreset, HTMLPreset,
    Document, Section, SubSection  # 👈 Added SubSection
)

class Command(IngressCommand):
    help = "Ingress documents with fake data: presets, departments, tags, documents, sections, and subsections"

    def process(self, _):
        # Dashboard block
        self.create_dashboard_item(
            title="Documents",
            icon="file-text",
            description="Presets, departments, and structured documents with sections and subsections.",
            link="/documents/"
        )

        self.stdout.write("Starting document ingress...")

        # Create users if none exist
        users = User.objects.all()
        if not users.exists():
            users = [User.objects.create_user(username=f"user{i}", password="pass") for i in range(1, 4)]

        # Create tags
        tag_names = ['Research', 'Internal', 'Public', 'Confidential', 'Draft']
        tags = [Tag.objects.get_or_create(name=name)[0] for name in tag_names]

        # Create departments
        departments = []
        for i in range(3):
            dept = Department.objects.create(
                name=f"Department {i+1}",
                owner=random.choice(users)
            )
            departments.append(dept)

        # Create LaTeX presets
        latex_presets = []
        for i in range(2):
            preset = LatexPreset.objects.create(
                name=f"LaTeX Preset {i+1}",
                engine='latex',
                document_class='article',
                preamble=lorem.paragraph(),
                packages=["amsmath", "geometry", "graphicx"],
                footer_note=lorem.sentence()
            )
            latex_presets.append(preset)

        # Create HTML presets
        html_presets = []
        for i in range(2):
            preset = HTMLPreset.objects.create(
                name=f"HTML Preset {i+1}",
                engine='html',
                template_name=f"template_{i+1}.html",
                css_classes={"body": "bg-white text-black", "header": "font-bold"},
                script_includes=["https://cdn.example.com/script.js"],
                footer_html="<footer>Generated by Copilot</footer>"
            )
            html_presets.append(preset)

        # Create documents
        for i in range(10):
            doc = Document.objects.create(
                title=f"Ingress Document {i+1}",
                preset=random.choice(latex_presets + html_presets),
                summary=lorem.sentence(),
                created_by=random.choice(users),
                department=random.choice(departments),
                created_at=timezone.now()
            )
            doc.tags.set(random.sample(tags, k=random.randint(1, 3)))

            # Create sections
            for j in range(random.randint(2, 5)):
                section = Section.objects.create(
                    document=doc,
                    title=f"Section {j + 1}",
                    order=j,
                    content=lorem.paragraph()
                )

                # Create subsections
                for k in range(random.randint(1, 3)):
                    SubSection.objects.create(
                        section=section,
                        order=k,
                        title=f"SubSection {j + 1}.{k + 1}",
                        content=lorem.paragraph()
                    )

        self.stdout.write(self.style.SUCCESS("Ingress complete. Documents seeded successfully!"))
